def themed_items(parts):
    items = []
    for p in parts:
        name, _, color = p.partition(":")
        if name.startswith(("body/", "human/", "orc/", "wolf/", "minotaur/", "reptile/", "goblin/", "undead/")):
            item = {"id": name} if name.startswith("body/") else H(name)
            if name.startswith(("orc/", "wolf/", "minotaur/", "reptile/", "goblin/", "undead/")):
                item = {"id": next((i for i in ITEMS if i.endswith("/" + name.split("/")[1])), "")}
        else:
            item = it(name)
        if not item or item["id"] not in ITEMS:
            continue
        if color:
            item["color"] = color
        items.append(item)
    return items


