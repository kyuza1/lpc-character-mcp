def H(name):  # head
    return {"id": f"head/heads/{name}"}


def find(suffix):
    """Item id that ends with `suffix` (so the script survives folder reshuffles)."""
    hits = [i for i in ITEMS if i.endswith("/" + suffix) or i == suffix]
    return hits[0] if hits else None


def it(suffix, color=None, variant=None):
    item_id = find(suffix)
    if not item_id:
        return None
    out = {"id": item_id}
    if color:
        out["color"] = color
    if variant:
        out["variant"] = variant
    return out


