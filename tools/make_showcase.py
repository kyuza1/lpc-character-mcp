def random_hero(rng, n):
    body = rng.choice(["male", "female"])
    items = server.random_items(body, random.Random(1000 + n))
    kit = []
    if rng.random() < 0.7:
        kit.append(it(rng.choice(WEAPONS)))
    if rng.random() < 0.35:
        kit.append(it(rng.choice(SHIELDS)))
    if rng.random() < 0.4:
        items = [i for i in items if not i["id"].startswith("headwear/")]
        kit.append(it(rng.choice(HEADGEAR)))
    return body, items + [k for k in kit if k and "walk" in item_animations(k["id"], body)]


def standing(items, body, col=0, direction=2):
    comp = render._compose(items, body, ["walk"])
    if "error" in comp:
        return None
    img = dict((a, i) for a, i, _ in comp["rows"])["walk"]
    return img.crop((col * F, direction * F, (col + 1) * F, (direction + 1) * F))


def grass(w, h, seed=7):
    rng = random.Random(seed)
    img = Image.new("RGBA", (w, h), (74, 138, 52, 255))
    px = img.load()
    for y in range(h):
        for x in range(w):
            r = rng.random()
            if r < 0.10:
                px[x, y] = (62, 120, 44, 255)
            elif r < 0.16:
                px[x, y] = (88, 156, 62, 255)
    for _ in range(w * h // 90):  # tufinhos de grama
        x, y = rng.randrange(1, w - 1), rng.randrange(2, h)
        for dy in range(rng.choice([2, 3])):
            px[x, y - dy] = (104, 176, 70, 255)
    return img


def showcase(cols=8, rows=6):
    rng = random.Random(42)
    people = [(b, themed_items(p)) for b, p in THEMED]
    n = 0
    while len(people) < cols * rows:
        people.append(random_hero(rng, n))
        n += 1
    rng.shuffle(people)
    sheet = grass(cols * F, rows * F)
    for k, (body, items) in enumerate(people[: cols * rows]):
        cell = standing(items, body)
        if cell is not None:
            sheet.alpha_composite(cell, ((k % cols) * F, (k // cols) * F))
    sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(DOCS / "showcase.png")


def walking(count=8):
    rng = random.Random(5)
    people = [(b, themed_items(p)) for b, p in THEMED[:count // 2]]
    n = 100
    while len(people) < count:
        people.append(random_hero(rng, n))
        n += 1
    bg = grass(count * F, F + 8, seed=3)
    frames = []
    for col in range(1, 9):  # ciclo do walk (o quadro 0 é a pose parada)
        frame = bg.copy()
        for k, (body, items) in enumerate(people):
            cell = standing(items, body, col=col)
            if cell is not None:
                frame.alpha_composite(cell, (k * F, 4))
        frames.append(frame.resize((frame.width * 2, frame.height * 2), Image.NEAREST).convert("RGB"))
    frames[0].save(DOCS / "walk.gif", save_all=True, append_images=frames[1:], duration=110, loop=0)


